/**
 * Fold keys: one key for every spelling a disk treats as one file name.
 *
 * Three profiles, one per kind of workspace disk:
 *   - `none`: tidying only, for a disk that keeps every spelling apart.
 *   - `nfd`: canonical decomposition with canonical ordering, which is what a
 *     case-sensitive APFS volume folds.
 *   - `caseless`: NFD of the full case folding of NFD, the Unicode canonical
 *     caseless match, which is what a case-insensitive APFS volume folds. It
 *     applies no Turkic mapping (dotless i stays apart from I), no
 *     compatibility folding (fullwidth A stays apart from A) and removes no
 *     ignorable character.
 * Every fold applies per path segment after `tidyPath`, and never turns a
 * backslash into a separator.
 *
 * WHY A TABLE. Each runtime's own `normalize` follows the Unicode version it
 * was built with, and JavaScript has no case folding at all, so the folds read
 * the shared table in fold_data/fold_table.json (Unicode 17.0.0, generated by
 * tools/gen_fold_table.js). The Python coordinator reads a byte-identical copy,
 * so both coordinators compute the same key for the same name.
 *
 * Callers check `exceedsFoldLimit` first: a name over the limit is never
 * folded, matching the Python coordinator's refusal of a path over 1024
 * characters. The folds themselves stay O(n log n) at any length.
 */
import foldData from './fold_data/fold_table.json' with { type: 'json' };

export type FoldProfile = 'caseless' | 'nfd' | 'none';
export type FoldingProfile = Exclude<FoldProfile, 'none'>;

/** The Unicode version of the shared table, which /status advertises beside the profile. */
export const FOLD_TABLE_UNICODE_VERSION: string = foldData.unicode_version;

export const FOLD_LENGTH_LIMIT = 1024;

// Hangul syllables carry no mapping in the UCD; Unicode defines them by arithmetic.
const HANGUL_S_BASE = 0xac00;
const HANGUL_L_BASE = 0x1100;
const HANGUL_V_BASE = 0x1161;
const HANGUL_T_BASE = 0x11a7;
const HANGUL_L_COUNT = 19;
const HANGUL_V_COUNT = 21;
const HANGUL_T_COUNT = 28;
const HANGUL_N_COUNT = HANGUL_V_COUNT * HANGUL_T_COUNT;
const HANGUL_S_COUNT = HANGUL_L_COUNT * HANGUL_N_COUNT;

function parseHexSequence(sequence: string): number[] {
  return sequence.split(' ').map((codePoint) => parseInt(codePoint, 16));
}

function pairKey(first: number, second: number): number {
  return first * 0x110000 + second;
}

function sequenceMap(record: Record<string, string>): Map<number, number[]> {
  return new Map(
    Object.entries(record).map(([codePoint, sequence]) => [
      parseInt(codePoint, 16),
      parseHexSequence(sequence),
    ])
  );
}

const DECOMPOSITION = sequenceMap(foldData.table.decomposition);
const CASE_FOLDING = sequenceMap(foldData.table.case_folding);
const COMBINING_CLASS = new Map(
  Object.entries(foldData.table.combining_class).map(([codePoint, combiningClass]) => [
    parseInt(codePoint, 16),
    combiningClass,
  ])
);
const COMPOSITION = new Map(
  Object.entries(foldData.table.composition).map(([pair, composite]) => {
    const [first, second] = parseHexSequence(pair);
    return [pairKey(first, second), parseInt(composite, 16)];
  })
);

function combiningClass(codePoint: number): number {
  return COMBINING_CLASS.get(codePoint) ?? 0;
}

function toCodePoints(text: string): number[] {
  const codePoints: number[] = [];
  for (const character of text) codePoints.push(character.codePointAt(0) as number);
  return codePoints;
}

function fromCodePoints(codePoints: readonly number[]): string {
  return codePoints.map((codePoint) => String.fromCodePoint(codePoint)).join('');
}

function decomposeCodePoint(codePoint: number): readonly number[] {
  const syllableIndex = codePoint - HANGUL_S_BASE;
  if (syllableIndex < 0 || syllableIndex >= HANGUL_S_COUNT) {
    return DECOMPOSITION.get(codePoint) ?? [codePoint];
  }
  const leading = HANGUL_L_BASE + Math.floor(syllableIndex / HANGUL_N_COUNT);
  const vowel = HANGUL_V_BASE + Math.floor((syllableIndex % HANGUL_N_COUNT) / HANGUL_T_COUNT);
  const trailing = HANGUL_T_BASE + (syllableIndex % HANGUL_T_COUNT);
  return trailing === HANGUL_T_BASE ? [leading, vowel] : [leading, vowel, trailing];
}

/**
 * Each run of non-starters sorted by combining class. Array.prototype.sort is
 * stable, which canonical ordering needs (marks of one class keep their
 * order), and O(n log n), so a long run of marks in reverse order stays cheap.
 */
function canonicalOrder(codePoints: readonly number[]): number[] {
  const ordered: number[] = [];
  let marks: number[] = [];
  const flushMarks = (): void => {
    marks.sort((left, right) => combiningClass(left) - combiningClass(right));
    for (const mark of marks) ordered.push(mark);
    marks = [];
  };
  for (const codePoint of codePoints) {
    if (combiningClass(codePoint) !== 0) {
      marks.push(codePoint);
      continue;
    }
    flushMarks();
    ordered.push(codePoint);
  }
  flushMarks();
  return ordered;
}

function canonicalDecomposition(codePoints: readonly number[]): number[] {
  return canonicalOrder(codePoints.flatMap((codePoint) => decomposeCodePoint(codePoint)));
}

function caseFold(codePoints: readonly number[]): number[] {
  return codePoints.flatMap((codePoint) => CASE_FOLDING.get(codePoint) ?? [codePoint]);
}

function composeHangul(first: number, second: number): number | undefined {
  const leadingIndex = first - HANGUL_L_BASE;
  const vowelIndex = second - HANGUL_V_BASE;
  if (
    leadingIndex >= 0 &&
    leadingIndex < HANGUL_L_COUNT &&
    vowelIndex >= 0 &&
    vowelIndex < HANGUL_V_COUNT
  ) {
    return HANGUL_S_BASE + (leadingIndex * HANGUL_V_COUNT + vowelIndex) * HANGUL_T_COUNT;
  }
  const syllableIndex = first - HANGUL_S_BASE;
  const trailingIndex = second - HANGUL_T_BASE;
  const isLvSyllable =
    syllableIndex >= 0 && syllableIndex < HANGUL_S_COUNT && syllableIndex % HANGUL_T_COUNT === 0;
  return isLvSyllable && trailingIndex > 0 && trailingIndex < HANGUL_T_COUNT
    ? first + trailingIndex
    : undefined;
}

/**
 * Canonical composition of a canonically ordered sequence. A code point joins
 * the last starter unless a mark kept between them has the same or a higher
 * class (any kept starter would itself be the last starter). In canonical
 * order the last mark kept has the highest class of those between, so it
 * alone decides.
 */
function canonicalComposition(codePoints: readonly number[]): number[] {
  const composed: number[] = [];
  let starterIndex = -1;
  let lastClass = 0;
  for (const codePoint of codePoints) {
    const codePointClass = combiningClass(codePoint);
    const isAdjacent = starterIndex === composed.length - 1;
    const isBlocked = !isAdjacent && lastClass >= codePointClass;
    if (starterIndex >= 0 && !isBlocked) {
      const starter = composed[starterIndex] as number;
      const composite =
        composeHangul(starter, codePoint) ?? COMPOSITION.get(pairKey(starter, codePoint));
      if (composite !== undefined) {
        composed[starterIndex] = composite;
        continue;
      }
    }
    if (codePointClass === 0) starterIndex = composed.length;
    lastClass = codePointClass;
    composed.push(codePoint);
  }
  return composed;
}

function segmentKey(segment: string, profile: FoldingProfile): number[] {
  const decomposed = canonicalDecomposition(toCodePoints(segment));
  // The inner decomposition comes first because U+0345 must reach its
  // canonical place among the marks before it folds to a starter.
  return profile === 'nfd' ? decomposed : canonicalDecomposition(caseFold(decomposed));
}

function mapSegments(path: string, fold: (segment: string) => string): string {
  return path.split('/').map(fold).join('/');
}

/**
 * Collapse repeated `/` and drop `.` segments, as the kernel does when it
 * looks a path up. A leading and a trailing `/` stay, and `..`, a backslash
 * and the text of every other segment are left exactly as given: resolving
 * `..` by text is wrong across a link, and refusing it is the caller's job.
 */
export function tidyPath(path: string): string {
  const segments = path.split('/').filter((segment) => segment !== '' && segment !== '.');
  const leading = path.startsWith('/') ? '/' : '';
  const trailing = path.endsWith('/') && segments.length > 0 ? '/' : '';
  return `${leading}${segments.join('/')}${trailing}`;
}

export function foldKey(path: string, profile: FoldProfile): string {
  const tidied = tidyPath(path);
  if (profile === 'none') return tidied;
  return mapSegments(tidied, (segment) => fromCodePoints(segmentKey(segment, profile)));
}

/**
 * The profile's key recomposed to NFC, for matching against policy globs: a
 * glob's `?` then meets one composed letter, as it does for a name typed in
 * NFC. A disk that folds nothing matches globs against the name as given.
 */
export function policyFold(path: string, profile: FoldingProfile): string {
  return policyFoldText(tidyPath(path), profile);
}

/**
 * `policyFold` of `text` exactly as given, without tidying: a glob's literal
 * characters fold where they stand, and tidying a run such as the lone `.` in
 * `*.*` would change what the glob matches.
 */
export function policyFoldText(text: string, profile: FoldingProfile): string {
  return mapSegments(text, (segment) =>
    fromCodePoints(canonicalComposition(segmentKey(segment, profile)))
  );
}

/**
 * `policyFoldText` of one code point when the fold is one code point too, else
 * undefined: a glob class stands for one character, so only such a fold can
 * be written into one. Looked up, not worked out: a class fold asks this of
 * every member of every class, and an untrack request's entries can hold
 * thousands of them.
 */
export function foldOneCodePoint(character: string, profile: FoldingProfile): string | undefined {
  const { folds } = singleFoldIndex(profile);
  return folds.has(character) ? folds.get(character) : character;
}

/** Every code point whose `foldOneCodePoint` is `target`, over all of Unicode. */
export function singleFoldPreimages(target: string, profile: FoldingProfile): readonly string[] {
  const others = singleFoldIndex(profile).preimages.get(target) ?? [];
  return foldOneCodePoint(target, profile) === target ? [target, ...others] : others;
}

/** The one-code-point folds of the code points the table maps, both ways. */
interface SingleFoldIndex {
  /** Each one's `foldOneCodePoint`. */
  readonly folds: ReadonlyMap<string, string | undefined>;
  /** The ones that fold to another code point, by what they fold to. */
  readonly preimages: ReadonlyMap<string, string[]>;
}

// Built on first use, so a disk of one profile never pays for the other's.
const singleFoldIndexes = new Map<FoldingProfile, SingleFoldIndex>();

function singleFoldIndex(profile: FoldingProfile): SingleFoldIndex {
  let index = singleFoldIndexes.get(profile);
  if (index === undefined) {
    index = buildSingleFoldIndex(profile);
    singleFoldIndexes.set(profile, index);
  }
  return index;
}

/**
 * Only a code point the table maps can fold to anything but itself (a Hangul
 * syllable decomposes and recomposes to itself), so reading the table's keys
 * finds every fold that is not the code point itself; both coordinators read
 * the same table, so they find the same ones.
 */
function buildSingleFoldIndex(profile: FoldingProfile): SingleFoldIndex {
  const folds = new Map<string, string | undefined>();
  const preimages = new Map<string, string[]>();
  for (const codePoint of new Set([...DECOMPOSITION.keys(), ...CASE_FOLDING.keys()])) {
    const source = String.fromCodePoint(codePoint);
    const folded = policyFoldText(source, profile);
    const fold = toCodePoints(folded).length === 1 ? folded : undefined;
    folds.set(source, fold);
    if (fold === undefined || fold === source) continue;
    const sources = preimages.get(fold);
    if (sources === undefined) preimages.set(fold, [source]);
    else sources.push(source);
  }
  return { folds, preimages };
}

export function exceedsFoldLimit(text: string): boolean {
  // A code point takes one or two UTF-16 units, so a string this short cannot be over.
  if (text.length <= FOLD_LENGTH_LIMIT) return false;
  let codePointCount = 0;
  for (const _character of text) {
    codePointCount += 1;
    if (codePointCount > FOLD_LENGTH_LIMIT) return true;
  }
  return false;
}
